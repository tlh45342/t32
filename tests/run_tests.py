    compile_and_execute(cc, "parentheses_override", 20, "parentheses override precedence")
    compile_and_execute(cc, "parentheses_nested", 46, "nested parentheses")
    compile_and_execute(cc, "assignment_complex_expression", 11, "complex assignment expression")
    compile_and_execute(cc, "assignment_parenthesized_expression", 16, "parenthesized assignment expression")

    # Stage 10: comparison expressions produce canonical integer 0 or 1.
