    compile_and_execute(cc, "local_add_constant", 8, "local plus constant")
    compile_and_execute(cc, "constant_add_local", 8, "constant plus local")
    compile_and_execute(cc, "local_add_local", 10, "local plus local")
    compile_and_execute(cc, "assignment_add", 6, "addition assignment")
    compile_and_execute(cc, "assignment_identifier_rhs", 5, "identifier assignment")
    compile_and_execute(cc, "assignment_expression_rhs", 9, "constant-expression assignment")
    compile_and_execute(cc, "assignment_repeated_increment", 3, "repeated increment")
    compile_and_execute(cc, "add_negative", 0xFFFFFFFB, "negative addition")

    compile_and_execute(cc, "return_sub_constants", 7, "constant minus constant")
    compile_and_execute(cc, "local_sub_constant", 7, "local minus constant")
    compile_and_execute(cc, "constant_sub_local", 7, "constant minus local")
    compile_and_execute(cc, "local_sub_local", 0, "local minus local")
    compile_and_execute(cc, "assignment_sub", 4, "subtraction assignment")
    compile_and_execute(cc, "assignment_constant_sub_local", 7, "constant-minus-local assignment")
    compile_and_execute(cc, "assignment_repeated_decrement", 1, "repeated decrement")
    compile_and_execute(cc, "sub_negative_result", 0xFFFFFFF8, "negative subtraction result")
    compile_and_execute(cc, "sub_negative_operand", 8, "subtract negative operand")

    compile_and_execute(cc, "return_mul_constants", 42, "constant times constant")
    compile_and_execute(cc, "local_mul_constant", 42, "local times constant")
    compile_and_execute(cc, "constant_mul_local", 42, "constant times local")
    compile_and_execute(cc, "local_mul_local", 36, "local times local")
    compile_and_execute(cc, "assignment_mul", 15, "multiplication assignment")
    compile_and_execute(cc, "assignment_constant_mul_local", 15, "constant-times-local assignment")
