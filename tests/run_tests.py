    compile_and_execute(cc, "mul_negative_result", 0xFFFFFFF4, "negative multiplication result")
    compile_and_execute(cc, "mul_two_negatives", 12, "two-negative multiplication")


    compile_and_execute(cc, "expression_divide", 4, "constant divided by constant")
    compile_and_execute(cc, "local_div_constant", 7, "local divided by constant")
    compile_and_execute(cc, "constant_div_local", 7, "constant divided by local")
    compile_and_execute(cc, "local_div_local", 1, "local divided by local")
    compile_and_execute(cc, "assignment_div", 7, "division assignment")
    compile_and_execute(cc, "assignment_constant_div_local", 7, "constant-divided-by-local assignment")
    compile_and_execute(cc, "assignment_repeated_half", 16, "repeated halving")
    compile_and_execute(cc, "div_negative_dividend", 0xFFFFFFFB, "negative dividend division")
    compile_and_execute(cc, "div_negative_divisor", 0xFFFFFFFB, "negative divisor division")
    compile_and_execute(cc, "div_two_negatives", 5, "two-negative division")

    compile_and_execute(cc, "return_rem_constants", 2, "constant remainder constant")
    compile_and_execute(cc, "local_rem_constant", 2, "local remainder constant")
    compile_and_execute(cc, "constant_rem_local", 2, "constant remainder local")
    compile_and_execute(cc, "local_rem_local", 0, "local remainder local")
    compile_and_execute(cc, "assignment_rem", 2, "remainder assignment")
